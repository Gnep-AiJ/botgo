assert.match(home, /scroll-cue-icon/);
assert.match(home, /assets\/botgo-rocket\.svg/);
assert.match(home, /class="product-flow"/);
assert.match(home, /class="flow-steps"/);
assert.match(home, /登录或注册/);
assert.match(home, /充值账户/);
assert.match(home, /打开本地项目/);
assert.match(home, /选择模型 开始对话/);
assert.match(home, /class="flow-gallery"/);
assert.ok(home.indexOf('botgo-client-start-original.png') < home.indexOf('botgo-client-connect-original.png'));
