assert.match(account, /workspace-redirect\.js/);
assert.doesNotMatch(home, /连接本地项目，选择可用模型，在同一个窗口查看任务进展/);
assert.doesNotMatch(home, /打开项目 选择模型 处理任务|下载 登录 开始|使用 BotGo 账户下载/);
