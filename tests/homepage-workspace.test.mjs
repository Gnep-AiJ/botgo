assert.ok(existsSync(join(root, 'dist', 'assets', 'botgo-balance-wave-user.webp')));
assert.ok(existsSync(join(root, 'dist', 'assets', 'botgo-rocket.svg')));
assert.ok(!existsSync(join(root, 'dist', 'download.html')));
