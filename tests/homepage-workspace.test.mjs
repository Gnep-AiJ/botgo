assert.doesNotMatch(home, /网页对话|BotGo Agent CLI|data-workspace="web"/);
assert.doesNotMatch(account, /id="desktop-install-dialog"|id="subscription-dialog"|id="account-dialog"/);
assert.match(home, /data-recharge-option/);
assert.match(home, /gnepaij@qq\.com/);
assert.doesNotMatch(account, /chat-form|chat-log|serviceWeb|data-copy-install|Agent CLI/);
assert.match(accountScript, /\/auth\/request-login-code/);
