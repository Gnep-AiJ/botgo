const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {createCredentialStore}=require('../opencode-desktop/runtime/credential-store.cjs');
const base=path.resolve('artifacts/verification/credential-tests');
fs.mkdirSync(base,{recursive:true});
const directory=fs.mkdtempSync(path.join(base,'case-'));
const filePath=path.join(directory,'device.enc');
let readable=true;
const safeStorage={isEncryptionAvailable:()=>true,encryptString:value=>Buffer.from(value),decryptString:bytes=>{if(!readable)throw Error('decrypt failed');return bytes.toString();}};
const store=createCredentialStore({filePath,safeStorage});
store.save({deviceToken:'bgdt_fixture'});
const before=fs.readFileSync(filePath);
readable=false;
assert.throws(()=>store.load(),error=>error.code==='CREDENTIAL_UNREADABLE');
assert.deepEqual(fs.readFileSync(filePath),before,'reading never discards credentials');
store.archiveUnreadable();
const archived=fs.readdirSync(directory).find(name=>name.startsWith('device.enc.unreadable-'));
assert.ok(archived);
assert.deepEqual(fs.readFileSync(path.join(directory,archived)),before);
assert.equal(store.load(),null);
readable=true;store.save({deviceToken:'bgdt_replacement'});
assert.equal(store.load().deviceToken,'bgdt_replacement');
assert.deepEqual(fs.readFileSync(path.join(directory,archived)),before,'explicit reauthentication preserves encrypted backup');
console.log('Credentials: unreadable sign-in is preserved and explicit recovery permits a replacement');
