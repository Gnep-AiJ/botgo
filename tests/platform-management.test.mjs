import assert from "node:assert/strict";
import fs from "node:fs";

const read = (file) => fs.readFileSync(file, "utf8");
const platform = read("worker/src/platform-admin.js");
const alipay = read("worker/src/alipay-payment.js");
const alipayRoutes = read("worker/src/alipay-routes.js");
const admin = read("admin.html");
const workspace = read("workspace.html");
const workspaceBilling = read("workspace-billing.js");
const headers = read("_headers");
const desktop = JSON.parse(read("desktop/package.json"));

for (const file of ["worker/migrations/0008_upstream_profiles.sql", "worker/migrations/0009_billing.sql", "worker/migrations/0010_desktop_releases.sql", "worker/migrations/0011_upstream_routes.sql", "worker/migrations/0012_alipay_billing.sql", "worker/migrations/0013_credit_balance_cents.sql", "admin-platform.js", "workspace-billing.js"]) assert.ok(fs.existsSync(file), `${file} must exist`);
assert.match(platform, /AES-GCM/, "upstream credentials must use authenticated encryption");
assert.match(platform, /UPSTREAM_CONFIG_KEY/, "encryption must depend on a Worker Secret");
const publicProfile = platform.match(/function publicProfile[\s\S]*?\n\}/)?.[0] || "";
assert.doesNotMatch(publicProfile, /apiKey|ciphertext|api_key_iv/, "admin APIs must not return a full or encrypted upstream key");
assert.match(platform, /probe\?\.status !== "ok"/, "a channel/model capability probe must pass before routing");
assert.match(platform, /web_chat.*desktop_codex/, "web and desktop must use independent route channels");
assert.match(platform, /upstream_route_history/, "route switches must retain rollback history");
assert.match(platform, /import-fallback/, "the current Worker upstream must be importable without exposing its key");
assert.match(platform, /url\.protocol !== "https:"/, "upstream URLs must require HTTPS");
assert.match(alipay, /alipay\.trade\.page\.pay/, "website checkout must use the Alipay page payment API");
assert.match(alipay, /signAlipayParams/, "website checkout must sign with the Worker Web Crypto implementation");
assert.match(alipayRoutes, /checkNotifySignV2|verifyNotify/, "payment notifications must be verified");
assert.match(workspaceBilling, /paymentHtml/, "the client must submit the SDK-generated payment form");
assert.match(workspaceBilling, /paymentUrl/, "the client must support the CSP-safe signed payment URL");
assert.match(workspaceBilling, /window\.open\("about:blank"/, "the client must open a dedicated payment window from the user gesture");
assert.match(workspaceBilling, /popup\.location\.replace/, "the client must navigate the dedicated window to the signed payment URL");
assert.match(workspaceBilling, /\/api\/billing\/query/, "the original page must poll the order status");
assert.match(headers, /form-action 'self' https:\/\/openapi\.alipay\.com https:\/\/openapi-sandbox\.dl\.alipaydev\.com/, "CSP must allow Alipay checkout form targets");
assert.match(platform, /套餐已停用/, "legacy subscription grants must reject writes");
assert.match(platform, /DESKTOP_RELEASES\.get/, "desktop downloads must stream from private R2");
assert.match(admin, /id="upstream-form"/, "admin must expose upstream management");
assert.match(admin, /id="order-list"/, "admin must expose recharge orders");
assert.doesNotMatch(admin, /邀请码|开通 Pro|兼容价格|data-admin-view="audit"/, "obsolete admin features must be removed");
assert.match(admin, /id="release-form"/, "admin must expose release management");
assert.match(admin, /data-admin-view="upstreams"/, "admin must use dedicated operational views");
assert.doesNotMatch(read("admin-platform.js"), /\bprompt\(/, "admin editing must not use browser prompt dialogs");
assert.match(workspace, /data-billing-balance/, "workspace must show the monetary balance");
assert.match(workspace, /data-recharge-option/, "workspace must expose preset recharge amounts");
assert.match(workspace, /id="recharge-amount"/, "workspace must expose a custom recharge amount");
assert.doesNotMatch(workspace, /购买 Pro/, "workspace must not present Pro subscription checkout");
assert.match(workspaceBilling, /amountCents/, "checkout must send the selected recharge amount");
assert.match(workspace, /id="desktop-download-link"/, "desktop dialog must expose the protected release download");
assert.equal(desktop.build.compression, "maximum", "desktop packaging must use maximum compression");
assert.ok(!desktop.build.files.includes("**/*"), "desktop packaging must use an explicit allowlist");

console.log("Platform management contract test passed");
