import assert from "node:assert/strict";
import fs from "node:fs";

const read = (file) => fs.readFileSync(file, "utf8");
const platform = read("worker/src/platform-admin.js");
const alipay = read("worker/src/alipay-payment.js");
const alipayRoutes = read("worker/src/alipay-routes.js");
const admin = read("admin.html");
const workspace = read("workspace.html");
const home = read("index.html");
const workspaceBilling = read("workspace-billing.js");
const nativeInstaller = read("opencode-desktop/installer.cjs");
const nativePrepare = read("opencode-desktop/prepare.mjs");

for (const file of ["worker/migrations/0008_upstream_profiles.sql", "worker/migrations/0009_billing.sql", "worker/migrations/0010_desktop_releases.sql", "worker/migrations/0011_upstream_routes.sql", "worker/migrations/0012_alipay_billing.sql", "worker/migrations/0013_credit_balance_cents.sql", "worker/migrations/0019_upstream_pools.sql", "admin-platform.js", "workspace-billing.js"]) assert.ok(fs.existsSync(file), `${file} must exist`);
assert.match(platform, /AES-GCM/, "upstream credentials must use authenticated encryption");
assert.match(platform, /UPSTREAM_CONFIG_KEY/, "encryption must depend on a Worker Secret");
const publicProfile = platform.match(/function publicProfile[\s\S]*?\n\}/)?.[0] || "";
assert.doesNotMatch(publicProfile, /apiKey|ciphertext|api_key_iv/, "admin APIs must not return a full or encrypted upstream key");
assert.match(platform, /member\.enabled&&probe\?\.status!==['"]ok['"]/, "every enabled route member must pass its channel/model capability probe");
assert.match(platform, /web_chat.*desktop_codex/, "web and desktop must use independent route channels");
assert.match(platform, /upstream_route_pool_history/, "route-pool changes must retain rollback history");
assert.doesNotMatch(platform, /import-fallback/, "Worker fallback import must be removed; upstreams are web-admin managed");
assert.match(platform, /url\.protocol !== "https:"/, "upstream URLs must require HTTPS");
assert.match(alipay, /signAlipayParams/, "legacy Alipay reconciliation must retain signature support");
assert.match(alipayRoutes, /checkNotifySignV2|verifyNotify/, "payment notifications must be verified");
assert.match(workspaceBilling, /\/api\/billing\/opcpay/, "checkout must use the OPCPay service");
assert.match(workspaceBilling, /paymentUrl/, "checkout must display the provider purchase link");
assert.doesNotMatch(workspaceBilling, /paymentHtml|\/api\/billing\/checkout/, "new checkout must not submit legacy Alipay forms");
assert.match(platform, /套餐已停用/, "legacy subscription grants must reject writes");
assert.match(platform, /DESKTOP_RELEASES\.get/, "desktop downloads must stream from private R2");
assert.match(admin, /id="upstream-form"/, "admin must expose upstream management");
assert.match(admin, /name="maxConcurrency"/, "admin must configure per-upstream concurrency");
assert.match(admin, /上游别名（可选）/, "admin must expose an optional upstream alias");
assert.match(admin, /id="open-route-dialog"/, "admin must expose route-pool management");
assert.doesNotMatch(admin, /import-fallback|导入当前配置/, "admin must not expose fallback configuration import");
assert.match(admin, /id="order-list"/, "admin must expose recharge orders");
assert.doesNotMatch(admin, /邀请码|开通 Pro|兼容价格|data-admin-view="audit"/, "obsolete admin features must be removed");
assert.match(admin, /id="release-form"/, "admin must expose release management");
assert.match(admin, /data-admin-view="upstreams"/, "admin must use dedicated operational views");
assert.doesNotMatch(read("admin-platform.js"), /\bprompt\(/, "admin editing must not use browser prompt dialogs");
assert.doesNotMatch(read("admin-metering.js"), /meter-opencode|BotGoAgentAdmin/, "client route management belongs to the routing view, not metering");
assert.match(home, /data-billing-balance/, "home dialog must show the monetary balance");
assert.match(home, /id="recharge-plan"/, "home dialog must expose provider plans");
assert.doesNotMatch(home, /id="recharge-amount"/, "fixed plans must not accept a custom amount");
assert.doesNotMatch(workspace, /购买 Pro/, "workspace must not present Pro subscription checkout");
assert.match(workspaceBilling, /skuId: plan\.id, actionId:/, "checkout must send the selected SKU and retry identifier");
assert.match(home, /data-download/, "home must expose the protected release download");
assert.match(nativeInstaller, /asar: true/, "native packaging must archive application code");
assert.match(nativeInstaller, /files: \['out\/\*\*\/\*', '!out\/\*\*\/\*\.map', 'resources\/icons\/icon\.ico'\]/, "native packaging must use an explicit allowlist");
const releaseVersion = JSON.parse(read("package.json")).version;
assert.ok(nativePrepare.includes(`pkg.version='${releaseVersion}'`), "native desktop release identity must match the package version");

console.log("Platform management contract test passed");
