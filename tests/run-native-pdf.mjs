const transport=net.createServer(socket=>{socket.end(key+'\n');transport.close();});
await new Promise((resolve,reject)=>{transport.once('error',reject);transport.listen(pipe,resolve);});
const child=spawn(path.join(paths.source,'node_modules/electron/dist/electron.exe'),[path.join(paths.root,'opencode-desktop/pdf-smoke.cjs'),...process.argv.slice(2)],{cwd:paths.root,windowsHide:true,env:{...process.env,BOTGO_TEST_KEY_PIPE:pipe},stdio:['ignore','pipe','pipe']});
const scrub=value=>String(value).replaceAll(key,'[redacted]').replace(/(?:sk-|bgdt_|bgk_)[A-Za-z0-9_-]+/g,'[redacted]');
child.stdout.on('data',chunk=>process.stdout.write(scrub(chunk)));child.stderr.on('data',chunk=>process.stderr.write(scrub(chunk)));
const code=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('close',resolve);});key='';
process.exitCode=code;
