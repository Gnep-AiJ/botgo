import readline from 'node:readline';
import {spawn} from 'node:child_process';
import path from 'node:path';
import net from 'node:net';
import {randomUUID} from 'node:crypto';
import paths from '../opencode-desktop/paths.cjs';
if(process.stdin.isTTY)process.stdin.setRawMode(true);
const rl=readline.createInterface({input:process.stdin,terminal:false});
console.log('READY_FOR_KEY_STDIN');
let key=process.argv.includes('--links-only')?'sk-fixture':await new Promise(resolve=>rl.once('line',resolve));rl.close();
if(!/^sk-[A-Za-z0-9_-]+$/.test(key))throw Error('Invalid test credential');
