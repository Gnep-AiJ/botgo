import assert from 'node:assert/strict';
import fs from 'node:fs';
import {DatabaseSync} from 'node:sqlite';
import {conversationRoute,startConversationTurn} from '../worker/src/conversations.js';
const db=new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON');
for(const name of fs.readdirSync('worker/migrations').filter(n=>n.endsWith('.sql')).sort())db.exec(fs.readFileSync(`worker/migrations/${name}`,'utf8'));
db.exec("INSERT INTO accounts(id,email,password_hash) VALUES('alice','alice@example.invalid','unused'),('bob','bob@example.invalid','unused')");
function statement(query){let values=[];return{bind(...args){values=args;return this;},async first(){return db.prepare(query).get(...values)||null;},async all(){return {results:db.prepare(query).all(...values)};},async run(){return {meta:{changes:Number(db.prepare(query).run(...values).changes)}};}};}
const env={DB:{prepare:statement,async batch(items){db.exec('BEGIN');try{const rows=[];for(const item of items)rows.push(await item.run());db.exec('COMMIT');return rows;}catch(e){db.exec('ROLLBACK');throw e;}}}};
const call=(account,path='',method='GET',body)=>conversationRoute(new Request(`https://test.invalid/conversations${path}`,{method,...(body?{body:JSON.stringify(body)}:{})}),env,account,`/conversations${path.split('?')[0]}`);
assert.equal((await call(null)).status,401);
const created=await (await call('alice','','POST',{title:'我的第一段对话'})).json();
assert.equal((await (await call('bob')).json()).conversations.length,0);
assert.equal((await call('bob',`/${created.id}`)).status,404);
assert.equal((await call('bob',`/${created.id}`,'DELETE')).status,404);
const body={conversationId:created.id,requestId:crypto.randomUUID(),content:'你好',model:'gpt-5.6-sol'};
assert.equal((await startConversationTurn(env,'bob',body)).response.status,404);
const first=await startConversationTurn(env,'alice',body);assert.deepEqual(first.body.messages,[{role:'user',content:'你好'}]);
assert.equal((await startConversationTurn(env,'alice',body)).response.status,409);
assert.equal((await startConversationTurn(env,'alice',{...body,requestId:crypto.randomUUID()})).response.status,409);
assert.equal((await call('alice',`/${created.id}`,'DELETE')).status,409);
const bytes=new TextEncoder().encode('data: {"choices":[{"delta":{"content":"你好，世界"}}]}\n\ndata: [DONE]\n\n');
for(const byte of bytes)await first.history.push(new Uint8Array([byte]));
await first.history.finish('completed');
let detail=await (await call('alice',`/${created.id}`)).json();assert.equal(detail.messages[1].content,'你好，世界');assert.equal(detail.messages[1].state,'completed');
assert.equal((await startConversationTurn(env,'alice',body)).response.status,409,'replay after completion rejected');
const second=await startConversationTurn(env,'alice',{...body,content:'继续',requestId:crypto.randomUUID()});assert.equal(second.body.messages.length,3);
await second.history.push(new TextEncoder().encode('data: {"choices":[{"delta":{"content":"部分回复"}}]}\n\n'));
await second.history.finish('completed');
detail=await (await call('alice',`/${created.id}`)).json();assert.equal(detail.messages[3].state,'stopped','missing terminal must not be completed');
const third=await startConversationTurn(env,'alice',{...body,requestId:crypto.randomUUID()});await third.history.finish('failed');
assert.equal((await call('alice',`/${created.id}`,'DELETE')).status,200);
assert.equal(db.prepare('SELECT COUNT(*) n FROM web_chat_turns').get().n,0);
assert.equal((await call('alice',`/${created.id}`)).status,404);
assert.equal((await startConversationTurn(env,'alice',{...body,requestId:crypto.randomUUID()})).response.status,404);
assert.equal(db.prepare('SELECT COUNT(*) n FROM accounts').get().n,2);
db.close();console.log('Conversation persistence, isolation, replay protection, interruption, locking and deletion passed');
