import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const electron=path.join(root,'artifacts/opencode/node_modules/electron');
const require=createRequire(path.join(electron,'install.js'));
const pkg=require('./package.json');
if(pkg.version!=='42.3.3')throw Error('Unexpected Electron version');
const archive=process.argv[2];
if(!archive||path.basename(archive)!=='electron-v42.3.3-win32-x64.zip')throw Error('Expected completed Electron 42.3.3 Windows x64 zip');
const expected=require('./checksums.json')[path.basename(archive)];
if(!expected)throw Error('No pinned checksum available');
const digest=crypto.createHash('sha256');
for await(const chunk of fs.createReadStream(archive))digest.update(chunk);
const actual=digest.digest('hex');
if(actual!==expected)throw Error('Electron archive checksum mismatch');
const dest=path.join(electron,'dist');
if(fs.existsSync(dest))throw Error('Electron dist already exists; refusing overwrite');
await require('extract-zip')(archive,{dir:dest});
const version=fs.readFileSync(path.join(dest,'version'),'utf8').trim().replace(/^v/,'');
if(version!==pkg.version||!fs.existsSync(path.join(dest,'electron.exe')))throw Error('Incomplete Electron extraction');
fs.writeFileSync(path.join(electron,'path.txt'),'electron.exe');
console.log(JSON.stringify({version,sha256:actual,executable:path.join(dest,'electron.exe')}));
